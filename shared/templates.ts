import type { Asset, AssetCategory, BrandKit, FrameKey, ImageLayer, Layer, LayoutTemplate, Scene, TemplateSlot } from './types.ts';
import { bestContrast, contrastRatio, hexToRgb, colorDistance, nearestColor } from './color.ts';
import { estimateTextHeight, isDisplayRole } from './text.ts';
import { backdropFor, bestLogoFor } from './lint.ts';

export function frameKeyFor(width: number, height: number): FrameKey {
  const r = width / height;
  if (r >= 0.9) return '1:1';
  if (r >= 0.68) return '4:5';
  return '9:16';
}

export interface TemplateFill {
  /** slotId -> copy for text and CTA slots. */
  texts?: Record<string, string>;
  /** slotId -> image prompt for photo slots (generated by the image model). */
  imagePrompts?: Record<string, string>;
}

export interface BuiltTemplate {
  background: string;
  layers: (Layer & { slotId?: string })[];
  /** Image layers that need pixels from the image model. */
  toGenerate: { layerId: string; prompt: string }[];
}

const DEFAULT_FONT_RATIO: Record<string, number> = { headline: 0.09, subheadline: 0.045, offer: 0.07, body: 0.032, disclaimer: 0.018 };
const rid = () => Math.random().toString(36).slice(2, 7);

function pickAsset(kit: BrandKit, categories: AssetCategory[], color: string | undefined, used: Set<string>): Asset | undefined {
  const pool = kit.assets.filter((a) => categories.includes(a.category));
  if (!pool.length) return undefined;
  const score = (a: Asset) => {
    let s = used.has(a.id) ? 1000 : 0;
    if (color && a.colors?.[0]) s += colorDistance(hexToRgb(color), hexToRgb(a.colors[0]));
    return s;
  };
  return [...pool].sort((a, b) => score(a) - score(b))[0];
}

function closestRatioAsset(assets: Asset[], ratio: number): Asset | undefined {
  return [...assets]
    .filter((a) => a.width && a.height)
    .sort((a, b) => Math.abs(a.width! / a.height! - ratio) - Math.abs(b.width! / b.height! - ratio))[0];
}

/**
 * Turns a layout template into concrete layers for the given canvas. Brand assets fill shape/icon/logo slots,
 * text colours are chosen for contrast against what ends up beneath them, and photo slots are queued for generation.
 */
export function buildFromTemplate(
  template: LayoutTemplate,
  canvas: Pick<Scene, 'width' | 'height'>,
  kit: BrandKit,
  fill: TemplateFill = {},
): BuiltTemplate {
  const W = canvas.width, H = canvas.height;
  const key = frameKeyFor(W, H);
  const profile = kit.profile;
  const palette = profile?.palette.map((c) => c.hex.toUpperCase()) ?? ['#111111', '#FFFFFF'];
  const snap = (hex?: string) => (hex && /^#[0-9a-f]{6}$/i.test(hex) ? nearestColor(hex, palette).hex : undefined);
  const used = new Set<string>();
  const scene: Scene = { id: 'tmp', format: key, width: W, height: H, background: snap(template.background.color) ?? palette[0], layers: [] };
  const toGenerate: BuiltTemplate['toGenerate'] = [];

  if (template.background.useTemplateAsset) {
    const bgAsset = closestRatioAsset(kit.assets.filter((a) => a.category === 'background_template'), W / H);
    if (bgAsset) {
      scene.layers.push({ id: `bg_${rid()}`, type: 'image', name: 'Background', role: 'background', x: 0, y: 0, width: W, height: H, src: bgAsset.url, assetId: bgAsset.id, fit: 'cover' });
      used.add(bgAsset.id);
    }
  }

  const backdropColor = (x: number, y: number, w: number, h: number) => {
    const probe: Layer = { id: '__probe', type: 'shape', name: '', shape: 'rect', x, y, width: w, height: h, fill: '#000000' };
    scene.layers.push(probe);
    const b = backdropFor(scene, scene.layers.length - 1, kit.assets);
    scene.layers.pop();
    return b.kind === 'color' ? b.hex : undefined;
  };

  for (const slot of template.slots) {
    const f = slot.frames[key] ?? slot.frames['4:5'] ?? slot.frames['1:1'];
    if (!f) continue;
    const x = Math.round(f[0] * W), y = Math.round(f[1] * H), w = Math.round(f[2] * W), h = Math.round(f[3] * H);
    const base = { name: slot.role === 'other' ? slot.kind : slot.role, role: slot.role, x, y, width: w, height: h, slotId: slot.id };

    switch (slot.kind) {
      case 'card':
      case 'shape':
        scene.layers.push({ ...base, id: `shp_${rid()}`, type: 'shape', shape: 'rect', fill: snap(slot.color) ?? '#FFFFFF', cornerRadius: Math.round((slot.cornerRadiusRatio ?? (slot.kind === 'card' ? 0.03 : 0)) * W) });
        break;

      case 'decoration':
      case 'icon':
      case 'illustration':
      case 'product_photo': {
        const cats: AssetCategory[] = slot.kind === 'decoration' ? ['shape'] : slot.kind === 'icon' ? ['icon'] : slot.kind === 'illustration' ? ['illustration'] : ['product_photo'];
        const asset = pickAsset(kit, cats, slot.color, used);
        const prompt = fill.imagePrompts?.[slot.id];
        if (asset && !prompt) {
          used.add(asset.id);
          scene.layers.push({ ...base, id: `ast_${rid()}`, type: 'image', src: asset.url, assetId: asset.id, fit: slot.kind === 'product_photo' ? 'cover' : 'contain' });
        } else if (prompt || slot.kind === 'illustration') {
          const layer: ImageLayer = { ...base, id: `img_${rid()}`, type: 'image', src: '', fit: 'cover', prompt };
          scene.layers.push(layer);
          if (prompt) toGenerate.push({ layerId: layer.id, prompt });
        }
        break;
      }

      case 'photo': {
        const prompt = fill.imagePrompts?.[slot.id];
        const asset = prompt ? undefined : pickAsset(kit, ['photo'], undefined, used);
        const layer: ImageLayer = asset
          ? { ...base, id: `img_${rid()}`, type: 'image', src: asset.url, assetId: asset.id, fit: 'cover', cornerRadius: Math.round((slot.cornerRadiusRatio ?? 0) * W) }
          : { ...base, id: `img_${rid()}`, type: 'image', src: '', fit: 'cover', prompt, cornerRadius: Math.round((slot.cornerRadiusRatio ?? 0) * W) };
        if (asset) used.add(asset.id);
        scene.layers.push(layer);
        if (prompt) toGenerate.push({ layerId: layer.id, prompt });
        break;
      }

      case 'text': {
        const display = isDisplayRole(slot.role);
        const font = display ? profile?.fonts.headline : profile?.fonts.body;
        const text = fill.texts?.[slot.id] ?? slot.example ?? slot.role;
        const bg = backdropColor(x, y, w, h);
        let color = snap(slot.color) ?? (bg ? bestContrast(bg, palette) : palette[0]);
        if (bg && contrastRatio(color, bg) < (display ? 3 : 4.5)) color = bestContrast(bg, palette);
        const layer: Layer = {
          ...base, id: `txt_${rid()}`, type: 'text', text,
          fontFamily: font?.family ?? (display ? 'Anton' : 'Inter'), fontWeight: slot.fontWeight ?? font?.weight ?? (display ? 800 : 400),
          fontSize: Math.round((slot.fontSizeRatio ?? DEFAULT_FONT_RATIO[slot.role] ?? 0.032) * W),
          fill: color, align: slot.align ?? 'left', lineHeight: display ? 1.05 : 1.3,
        };
        layer.height = estimateTextHeight(layer);
        scene.layers.push(layer);
        break;
      }

      case 'cta': {
        const behind = backdropColor(x, y, w, h);
        let fillColor = snap(slot.color) ?? palette[Math.min(1, palette.length - 1)];
        if (behind && contrastRatio(fillColor, behind) < 1.6) {
          fillColor = [...palette].sort((a, b) => contrastRatio(b, behind) - contrastRatio(a, behind))
            .find((c) => contrastRatio(c, behind) >= 1.6 && contrastRatio(bestContrast(c, palette), c) >= 3) ?? bestContrast(behind, palette);
        }
        scene.layers.push({
          ...base, id: `shp_${rid()}`, type: 'shape', shape: 'rect', fill: fillColor, cornerRadius: Math.round(h / 2),
          label: fill.texts?.[slot.id] ?? slot.example ?? 'Learn more', labelColor: bestContrast(fillColor, palette),
          labelFontFamily: profile?.fonts.body.family ?? 'Inter', labelFontSize: Math.round(h * 0.38), labelFontWeight: 700,
        });
        break;
      }

      case 'logo': {
        const bg = backdropColor(x, y, w, h) ?? scene.background;
        const logo = bestLogoFor(bg, kit) ?? kit.assets.find((a) => a.category === 'logo');
        if (!logo) break;
        const aspect = logo.width && logo.height ? logo.height / logo.width : 0.4;
        const lw = Math.min(w, Math.round(h / aspect));
        scene.layers.push({ ...base, id: `ast_${rid()}`, type: 'image', width: lw, height: Math.round(lw * aspect), src: logo.url, assetId: logo.id, fit: 'contain' });
        break;
      }
    }
  }

  reflowText(scene.layers, W * 0.025);
  return { background: scene.background, layers: scene.layers, toGenerate };
}

/** Text that wraps to more lines than its slot allowed pushes the text/CTA slots below it down. */
function reflowText(layers: Layer[], gap: number): void {
  const flow = layers
    .filter((l) => l.type === 'text' || (l.type === 'shape' && !!l.label))
    .sort((a, b) => a.y - b.y);
  for (let i = 1; i < flow.length; i++) {
    const cur = flow[i];
    for (const prev of flow.slice(0, i)) {
      if (prev.type !== 'text') continue;
      const xOverlap = Math.min(prev.x + prev.width, cur.x + cur.width) - Math.max(prev.x, cur.x);
      const minTop = prev.y + prev.height + gap;
      if (xOverlap > 0 && cur.y < minTop && cur.y >= prev.y) cur.y = Math.round(minTop);
    }
  }
}

/** Compact template catalogue for the planner prompt. */
export function describeTemplates(templates: LayoutTemplate[]): string {
  return templates
    .map((t) => `- ${t.id} "${t.name}": ${t.description}\n  slots: ${t.slots.filter((s) => s.kind === 'text' || s.kind === 'cta' || s.kind === 'photo').map((s) => `${s.id} (${s.kind === 'text' ? s.role : s.kind}${s.maxWords ? `, ≤${s.maxWords} words` : ''})`).join(', ')}`)
    .join('\n');
}
